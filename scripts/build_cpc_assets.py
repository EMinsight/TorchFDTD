def scaling_tables() -> None:
    fwd = sty.read('paper_review/scaling-forward-3060.json')
    sfwd = sty.read('paper_review/scaling-forward-streamed-3060.json')
    rows = []
    for c in fwd['cases']:
        if 'median' not in c:
            continue
        rows.append([f"${c['n']}^3$", f"{c['cells'] / 1e6:.1f}", 'resident',
                     f"{c['cell_steps_per_second_loop'] / 1e9:.2f}",
                     f"{c['cells'] * fwd['steps'] / c['median']['wall_seconds'] / 1e9:.2f}",
                     f"{c['median']['peak_allocated_bytes'] / 1e9:.3f}"])
    for c in sfwd['cases']:
        if 'median' not in c:
            continue
        rows.append([f"${c['n']}^3$", f"{c['cells'] / 1e6:.1f}", f"streamed, $W={c['slab_width']}$", '',
                     f"{c['cell_steps_per_second_full'] / 1e9:.2f}", f"{c['median']['peak_allocated_bytes'] / 1e9:.3f}"])
    table('si-scaling-forward',
          f"Forward solves over grid size on the RTX 3060 with {fwd['steps']} steps, medians of three warmed runs. "
          'The resident rows are the dielectric sphere of Section 7.3, and the streamed rows the periodic slab with two '
          'point monitors and a uniform permittivity. Rates are in $10^9$ cell-steps per second, and the stepping rate '
          'counts the time-stepping loop alone. Peak device allocation is in GB.',
          'tab:si-scaling-forward', '@{}rrlrrr@{}',
          ['Grid', 'Cells ($10^6$)', 'Path', 'Stepping', 'Full solve', 'Peak (GB)'], rows)

    rows = []
    for n in (128, 192, 256, 320, 384):
        r = sty.read(f'paper_review/scaling-adjoint-3060-{n}.json')
        res = r['records'].get('cuda_resident')
        dram = r['records']['cuda_dram']
        rs = r['median_seconds']
        rows.append([f'${n}^3$',
                     f"{rs['cuda_resident']:.2f}" if res else 'above budget',
                     f"{median_peak(r, 'cuda_resident'):.2f}" if res else '',
                     f"{rs['cuda_dram']:.2f}", f"{median_peak(r, 'cuda_dram'):.2f}",
                     f"{median_peak(r, 'cuda_dram', 'sampled_peak_process_rss_bytes'):.1f}",
                     str(r['configuration']['slab_width']),
                     f"{rs['cuda_dram'] / rs['cuda_resident']:.1f}" if res else ''])
    table('si-scaling-adjoint',
          'Time to gradient of the dielectric adjoint fixture over grid size on the RTX 3060, 128 steps, two '
          'checkpoints, temporal depth 8 and four host threads, medians of three warmed repetitions. Device peaks and '
          'the sampled host memory of the streamed process are in GB, and the last column is the ratio of streamed to '
          'resident time. At $384^3$ only the streamed adjoint fits the 10 GiB device budget.',
          'tab:si-scaling-adjoint', '@{}rrrrrrrr@{}',
          ['Grid', '\\shortstack{Resident\\\\(s)}', '\\shortstack{Resident\\\\peak}', '\\shortstack{Streamed\\\\(s)}',
           '\\shortstack{Streamed\\\\peak}', '\\shortstack{Host\\\\memory}', '$W$', 'Ratio'], rows)


def host_table() -> None:
    rows = []
    sources = [('A100 80GB PCIe, container with 4 cores', 'cpu-gpu-adjoint-256-{}-a100.json', ('dielectric', 'ade')),
               ('RTX 5880 Ada, workstation with 8 physical cores', 'cpu-gpu-adjoint-256-{}-5880.json', ('dielectric', 'ade')),
               ('RTX 3060, workstation with an i7-12700', 'paper_review/scaling-adjoint-3060-256.json', ('dielectric',))]
    for host, pattern, cases in sources:
        for case in cases:
            r = sty.read(pattern.format(case) if '{}' in pattern else pattern)
            cfg = r['configuration']
            assert cfg['size'] == 256 and cfg['steps'] == 128 and cfg['checkpoints'] == 2 and cfg['slab_width'] == 32
            assert cfg['temporal_depth'] == 8 and cfg['gpu_host_threads'] == 4 and cfg['dispersive'] == (case == 'ade')
            rs = r['median_seconds']
            rows.append([host, 'two-pole' if case == 'ade' else 'dielectric', f"{rs['cuda_resident']:.2f}",
                         f"{rs['cuda_dram']:.2f}", f"{rs['cuda_dram'] / rs['cuda_resident']:.1f}"])
            host = ''
    table('si-host',
          'Resident and host-streamed adjoints of the matched $256^3$ fixtures of Section 7.2 on three hosts, 128 steps, '
          'two checkpoints, slab width 32, temporal depth 8 and four host threads, medians of three warmed repetitions.',
          'tab:si-host', '@{}llrrr@{}', ['Host', 'Case', 'Resident (s)', 'Streamed (s)', 'Ratio'], rows)


def microring_table() -> None:
    c = sty.read('meep_comparison/microring_comparison.json')
    fits = {solver: [r for r in c['resonances'][solver] if isinstance(r, dict) and r.get('valid')]
            for solver in ('torchfdtd', 'meep')}
    assert len(fits['torchfdtd']) == len(fits['meep'])
    rows = []
    for a, b in zip(fits['torchfdtd'], fits['meep']):
        rows.append([f"{a['center_nm']:.4f}", f"{abs(a['center_nm'] - b['center_nm']):.1e}",
                     f"{a['q_loaded']:.1f}", f"{b['q_loaded']:.1f}", f"{a['extinction_db']:.3f}", f"{b['extinction_db']:.3f}"])
    table('si-microring',
          'Lorentzian fits of the four resonances of the microring of Section 6.3 from TorchFDTD and Meep on one grid. '
          'The loaded quality factors describe the spectra of the 5 ps window.',
          'tab:si-microring', '@{}rrrrrr@{}',
          ['\\shortstack{Resonance\\\\(nm)}', '\\shortstack{$|\\Delta\\lambda|$\\\\(nm)}', '\\shortstack{$Q$\\\\TorchFDTD}',
           '\\shortstack{$Q$\\\\Meep}', '\\shortstack{Extinction (dB)\\\\TorchFDTD}', '\\shortstack{Extinction (dB)\\\\Meep}'],
          rows)


def metalens_table() -> None:
    m = sty.read('meep_comparison/metalens_comparison.json')['3d']
    row = {r['name']: r for r in m['criteria_rows']}
    entries = [(1.55, {'focal_position_um': row['focal_position']['torchfdtd'], 'efficiency': row['efficiency']['torchfdtd'],
                       'fwhm_um': [row['fwhm_x']['torchfdtd'], row['fwhm_y']['torchfdtd']]},
                {'focal_position_um': row['focal_position']['meep'], 'efficiency': row['efficiency']['meep'],
                 'fwhm_um': [row['fwhm_x']['meep'], row['fwhm_y']['meep']]})]
    entries += [(e['wavelength_um'], e['torchfdtd'], e['meep']) for e in m['extra_wavelengths']]
    rows = []
    for wl, t, mp in sorted(entries, key=lambda e: e[0]):
        rows.append([f'{wl:.2f}', f"{t['focal_position_um']:.4f}", f"{mp['focal_position_um']:.4f}",
                     f"{t['fwhm_um'][0]:.4f}", f"{mp['fwhm_um'][0]:.4f}", f"{t['efficiency']:.5f}", f"{mp['efficiency']:.5f}"])
    table('si-metalens',
          'Focal position above the output plane, focal-plane full width at half maximum along $x$ and focusing '
          'efficiency of the pillar lens of Section 6.3 from TorchFDTD (T) and Meep (M) on one grid. Lengths are in '
          '\\micron{}.',
          'tab:si-metalens', '@{}rrrrrrr@{}',
          ['\\shortstack{Wavelength\\\\(\\micron{})}', 'Focus T', 'Focus M', 'FWHM T', 'FWHM M', 'Efficiency T',
           'Efficiency M'], rows)


