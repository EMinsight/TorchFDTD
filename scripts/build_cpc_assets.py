# ---------------------------------------------------------------- figures
def figures() -> None:
    sty.OUT = CPC / 'figures'
    p = sty.application_record()
    fig, ax = plt.subplots(figsize=(WIDTH * 0.56, 2.35))
    sty.application_check(ax, p)
    ax.set_title('End-to-end derivative check', loc='left', fontsize=8, pad=7, color=INK)
    fig.tight_layout()
    sty.save(fig, 'propagated-adjoint-check')

    fig, ax = plt.subplots(figsize=(WIDTH * 0.8, 1.7))
    sty.application_timeline(ax, p)
    ax.set_title('Streamed optical-objective evaluation', loc='left', fontsize=8, pad=7, color=INK)
    fig.tight_layout()
    sty.save(fig, 'propagated-adjoint-timeline')

    r = sty.read('paper_review/metagrating_showcase.json')
    s = r['spectra']
    wl = np.asarray(s['wavelength_um'])
    runs = [('fine', 'workflow_duration', 'final_binary', BLUE, (0, (3, 2)), 'final, 1600 steps'),
            ('fine', 'long_duration', 'final_binary', BLUE, '-', 'final, 6400 steps'),
            ('fine', 'long_duration', 'initial', GREY, '-', 'initial, 6400 steps')]
    fig, axes = plt.subplots(1, 2, figsize=(WIDTH, 2.35))
    ax = axes[0]
    for mesh, dur, design, color, ls, label in runs:
        e = s[mesh][dur][design]
        ax.plot(wl, np.abs(1 - np.asarray(e['T_total_plus_R'])), color=color, ls=ls, lw=1.1, label=label)
    ax.set(yscale='log', xlabel='Wavelength (µm)', ylabel='|1 $-$ (T + R)|', xlim=(wl.min(), wl.max()), ylim=(1e-8, 0.3))
    ax.legend(loc='lower left', fontsize=6.0)
    panel(ax, 'a', 'Energy balance, 25 nm mesh')
    ax = axes[1]
    for mesh, dur, design, color, ls, label in runs[:2]:
        ax.plot(wl, s[mesh][dur][design]['T_plus1'], color=color, ls=ls, lw=1.2, label=label)
    ax.axvline(1.0, color=LINE, lw=0.6, zorder=0)
    ax.set(xlabel='Wavelength (µm)', ylabel='+1 order efficiency', xlim=(wl.min(), wl.max()), ylim=(0, 0.7))
    ax.legend(loc='upper left', fontsize=6.0)
    panel(ax, 'b', 'Final layout')
    fig.tight_layout(w_pad=1.8)
    sty.save(fig, 'metagrating-convergence')


def main() -> None:
    sty.apply_style()
    sty.INPUTS.clear()
    scaling_tables()
    host_table()
    microring_table()
    metalens_table()
    metagrating_table()
    figures()
    provenance = {'generator': 'scripts/build_cpc_assets.py',
                  'generator_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  'inputs': {f'docs/validation/{k}': v for k, v in sorted(sty.INPUTS.items())}}
    (CPC / 'cpc-asset-provenance.json').write_bytes((json.dumps(provenance, indent=2) + '\n').encode('utf-8'))


if __name__ == '__main__':
    main()
