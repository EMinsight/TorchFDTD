"""Figures and tables used only by the Computer Physics Communications version (docs/paper-cpc).

Everything is read from validation records, and no solver runs. The shared figure style and the panel functions
come from scripts/build_paper_story_figures.py. Outputs go to docs/paper-cpc/figures and docs/paper-cpc/tables,
and docs/paper-cpc/cpc-asset-provenance.json lists the SHA-256 of every record read.
"""
from __future__ import annotations

import hashlib
import json
import statistics
from pathlib import Path

import numpy as np

import build_paper_story_figures as sty
from build_paper_story_figures import plt, panel, BLUE, TEAL, ORANGE, GREY, INK, MUTED, LINE, WIDTH

ROOT = Path(__file__).resolve().parents[1]
CPC = ROOT / 'docs/paper-cpc'
TABLES = CPC / 'tables'


def table(name: str, caption: str, label: str, spec: str, header: list[str], rows: list[list[str]], note: str = '') -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    lines = ['% Generated by scripts/build_cpc_assets.py from validation records.',
             '\\begin{table}[tbp]', '\\centering', '\\small', '\\renewcommand{\\arraystretch}{1.15}',
             f'\\caption{{{caption}}}', f'\\label{{{label}}}', f'\\begin{{tabular}}{{{spec}}}', '\\toprule',
             ' & '.join(header) + ' \\\\', '\\midrule']
    lines += [' & '.join(r) + ' \\\\' for r in rows]
    lines += ['\\bottomrule', '\\end{tabular}']
    if note:
        lines.append(note)
    lines.append('\\end{table}')
    (TABLES / f'{name}.tex').write_bytes(('\n'.join(lines) + '\n').encode('utf-8'))


def median_peak(record: dict, mode: str, key: str = 'peak_torch_cuda_allocated_bytes') -> float:
    return statistics.median(r[key] for r in record['records'][mode]) / 1e9


